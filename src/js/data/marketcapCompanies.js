/* =========================================================================
   PUBLIC COMPANIES BY MARKET CAP — name, ticker, home country.

   WHAT THIS FILE IS AND IS NOT. It is a list of NAMES. It carries no
   coordinates, and that is deliberate: a hand-typed latitude is a number
   nobody can check and the first thing to rot. Positions come from the Places
   API at run time, verified against the country recorded here, and cached — so
   every pin on the globe traces back to a live lookup rather than to a table
   somebody pasted in once.

   THE COUNTRY COLUMN IS WHAT MAKES THE LOOKUP TRUSTWORTHY. "Reliance" against
   a global index returns the Indian conglomerate; the ticker RS is an American
   steel distributor. Naming the country is what separates them, and it is also
   what lets a wrong-country result be REJECTED rather than drawn. Roughly one
   name in thirty cannot be pinned this way at all — a holding company with no
   public office, a name too generic to search — and those are reported as
   unresolved instead of being placed at a country centroid to round the map up
   to a whole number.

   Ordered by market capitalisation, richest first, as the source ranks them.
   For the full ranking rather than this cross-section, dump the listing page
   to a text file and run:

       node scripts/parse-marketcap.mjs <dump.txt> > companies.json

   then hand the result to `showCompanyList`. Mind the bill before you do: one
   company is one billed Places Text Search on FIRST resolution, so eleven
   thousand rows is eleven thousand requests. The cache means you pay once per
   company, ever — including for the ones that fail.
   ========================================================================= */

